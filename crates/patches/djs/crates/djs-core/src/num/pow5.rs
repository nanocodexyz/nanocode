//! 128-bit approximations of powers of five, shared by Ryu (formatting) and Eisel-Lemire
//! (parsing).
//!
//! The canonical value for an exponent `q` is
//!
//! ```text
//! C(q) = floor(5^q * 2^(127 - floor(log2(5^q))))      for -342 <= q <= 325
//! ```
//!
//! that is, 5^q normalized so that bit 127 is the top bit, rounded down. Both algorithms
//! need tables derived from these values (see `ryu_pow5`, `ryu_inv_pow5` and `lemire_pow5`).
//! The full table would be 10.7 KB; instead we store every 27th value and rebuild the others
//! as `C(27k) * 5^j` (j < 27, so 5^j is an exact u64), keeping the top 128 bits. That product
//! is short by at most 2 units in the last place, and a 2-bit correction per exponent makes
//! the result exact. The unit tests recompute every entry with exact big integer arithmetic.
//!
//! Size: 26 base values (416 bytes) + 27 small powers (216 bytes) + 42 correction words
//! (168 bytes) = 800 bytes.

pub(crate) const MIN_Q: i32 = -342;
pub(crate) const MAX_Q: i32 = 325;
const STRIDE: i32 = 27;
/// Index of `C(0)` in `BASE`: the first base exponent is `-13 * 27 = -351`.
const BASE_OFFSET: i32 = 13;

/// 5^j for 0 <= j <= 27.
pub(crate) const POW5_U64: [u64; 28] = {
    let mut t = [1u64; 28];
    let mut i = 1;
    while i < 28 {
        t[i] = t[i - 1] * 5;
        i += 1;
    }
    t
};

